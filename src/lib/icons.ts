/**
 * Pixel-art pictograms. Each row is a string; '#' is drawn with currentColor,
 * other characters are looked up in the optional palette, '.' is transparent.
 */
export interface PixelArt {
  rows: string[]
  palette?: Record<string, string>
}

export interface PixelLayer {
  fill: string
  d: string
}

export function toLayers(art: PixelArt): PixelLayer[] {
  const paths = new Map<string, string>()
  art.rows.forEach((row, y) => {
    ;[...row].forEach((ch, x) => {
      if (ch === '.' || ch === ' ') return
      const fill = ch === '#' ? 'currentColor' : (art.palette?.[ch] ?? 'currentColor')
      paths.set(fill, (paths.get(fill) ?? '') + `M${x} ${y}h1v1h-1z`)
    })
  })
  return [...paths].map(([fill, d]) => ({ fill, d }))
}

